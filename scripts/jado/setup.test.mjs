import assert from 'node:assert/strict';
import { mkdtemp, mkdir, cp, readFile, writeFile, rm, readdir, symlink, realpath } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { prepareInstall as buildInstall, applyInstall, hash } from './install.mjs';
import { prepareGlobal as buildGlobal, prepareLink, prepareLocalUpdate as buildLocalUpdate, managedBlock } from './setup.mjs';
import { fixturePackage, fixtureLegacyNames } from './fixtures.mjs';
const prepareInstall = options => buildInstall({loadPackage:fixturePackage,...options});
const prepareGlobal = options => buildGlobal({loadPackage:fixturePackage,...options});
const prepareLocalUpdate = options => buildLocalUpdate({loadPackage:fixturePackage,...options});
const run = promisify(execFile);
const fixture = await realpath(await mkdtemp(path.join(tmpdir(), 'jado-scopes-test-')));
const home = path.join(fixture, 'user');
const product = path.join(fixture, 'product');
const backups = [];
const apply = async plan => { const result = await applyInstall(plan, plan.revision); backups.push(result.backup); return result; };
try {
  await mkdir(path.join(home, '.agents/skills'), { recursive: true });
  await mkdir(path.join(home, '.claude')); await mkdir(path.join(home, '.codex'));
  await symlink(path.join(home, '.agents/skills'), path.join(home, '.claude/skills'));
  await symlink(path.join(home, '.agents/skills'), path.join(home, '.codex/skills'));
  await mkdir(product);
  const catalog = JSON.parse(await readFile('registry/jado-catalog.json'));
  const lock = JSON.parse(await readFile('jado/skill-lock.json'));
  const packages = [...new Set(catalog.skills.filter(s => s.design && s.path.startsWith('skills/')).map(s => s.path.split('/')[1]))];
  for (const name of packages) {
    const fresh = await fixturePackage(name,lock.skills[name],name,fixture);
    await cp(fresh.folder,path.join(home,'.agents/skills',name),{recursive:true});
  }
  await writeFile(path.join(home, '.agents/.skill-lock.json'), JSON.stringify(lock));
  await writeFile(path.join(home, '.codex/AGENTS.override.md'), '# Personal rules\nKeep product contracts.\n');
  await writeFile(path.join(home, '.codex/config.toml'), 'model_reasoning_effort = "high"\n[mcp_servers.existing]\ncommand = "keep-me"\n', { mode: 0o600 });
  const preexisting = path.join(home,'.agents/skills/impeccable/SKILL.md');
  const borrowed = path.join(home,'.jado/skills/impeccable/SKILL.md');
  await writeFile(preexisting, await readFile(preexisting, 'utf8') + '\nNewer external revision.\n');
  const borrowedBytes = await readFile(preexisting);
  const plan = await prepareGlobal({ tools: ['codex','claude-code','opencode'], userRoot: home });
  assert.deepEqual(await readdir(path.join(home, '.codex/agents')).catch(()=>[]), []);
  assert.equal(plan.summary.scope, 'global');
  assert(plan.changes.some(c => c.relative === '.agents/skills/impeccable' && c.before.directory));
  await apply(plan);
  assert(!(await readFile(borrowed)).equals(borrowedBytes),'JADO replaces the preexisting package');
  assert((await readFile(path.join(backups.at(-1),'.agents/skills/impeccable/SKILL.md'))).equals(borrowedBytes),'The replaced directory is recoverable');
  const managedLock = JSON.parse(await readFile(path.join(home,'.agents/.skill-lock.json')));
  assert(!managedLock.skills.impeccable,'The generic updater no longer owns JADO packages');
  assert((await readFile(path.join(home, '.codex/config.toml'), 'utf8')).startsWith('model_reasoning_effort = "high"\n[mcp_servers.existing]'));
  assert((await readFile(path.join(home, '.codex/AGENTS.override.md'), 'utf8')).startsWith('# Personal rules\nKeep product contracts.'));
  await assert.rejects(() => prepareGlobal({ tools: ['codex'], userRoot: home, component: 'skills' }), /change tools/);
  const actualCatalog = JSON.parse(await readFile(path.join(home, '.jado/registry/jado-catalog.json')));
  assert.equal(actualCatalog.skills.find(s => s.id === 'impeccable').path,'skills/impeccable/SKILL.md');
  assert.equal(await realpath(path.join(home, '.agents/skills/jado-flow')), path.join(home, '.jado/.agents/skills/jado-flow'));
  assert.equal((await readdir(path.join(home, '.codex/agents'))).length,5);
  assert.equal((await readdir(path.join(home, '.claude/agents'))).length,5);
  assert.equal((await readdir(path.join(home, '.config/opencode/agents'))).length,5);
  assert.equal((await prepareGlobal({ tools: ['codex','claude-code','opencode'], userRoot: home })).changes.length, 0, 'Global reinstall is a no-op');
  const retired = await fixtureLegacyNames(home);
  const migration = await prepareGlobal({tools:['codex','claude-code','opencode'],userRoot:home});
  for(const file of retired) assert(migration.changes.some(c => c.relative === file && c.after === null),'Upgrade retires the old owned names');
  await apply(migration);
  for(const file of retired) await assert.rejects(()=>readFile(path.join(home,file)),/ENOENT/);
  // A changed managed upstream package is replaced on reinstall.
  await writeFile(borrowed, Buffer.concat([borrowedBytes, Buffer.from('\nAnother upstream update.\n')]));
  const adoption = await prepareGlobal({ tools: ['codex','claude-code','opencode'], userRoot: home });
  assert(adoption.changes.some(c => c.relative === '.jado/skills/impeccable/SKILL.md'),'Reinstall restores JADO priority over a modified upstream package');
  await apply(adoption);
  const missing = path.join(home, '.jado/skills/research');
  await rm(missing, { recursive: true, force: true });
  const simulatedUpstream = async (name, record, skill, workspace) => {
    const {folder} = await fixturePackage(name,record,skill,workspace);
    await writeFile(path.join(folder, 'SKILL.md'), await readFile(path.join(folder, 'SKILL.md'), 'utf8') + '\nFresh upstream package.\n');
    return { folder, record: { ...record, skillFolderHash: hash(await readFile(path.join(folder, 'SKILL.md'))) } };
  };
  const singleUser = path.join(fixture, 'single-user'); await mkdir(singleUser);
  const unusedConfig = path.join(fixture, 'unused-provider-config'); await mkdir(unusedConfig);
  await symlink(unusedConfig, path.join(singleUser, '.claude'));
  const singlePlan = await prepareGlobal({ tools: ['codex'], userRoot: singleUser, loadPackage: simulatedUpstream });
  await apply(singlePlan);
  assert.deepEqual(await readdir(unusedConfig), [], 'Unselected provider directories are neither inspected nor written');
  assert.equal((await readdir(path.join(singleUser, '.codex/agents'))).length,5);
  const missingPlan = await prepareGlobal({ tools: ['codex','claude-code','opencode'], userRoot: home, loadPackage: simulatedUpstream });
  const missingRepeat = await prepareGlobal({ tools: ['codex','claude-code','opencode'], userRoot: home, loadPackage: simulatedUpstream });
  assert.equal(missingPlan.revision, missingRepeat.revision, 'A missing upstream package produces a stable review revision');
  const marker = path.join(home, '.jado/install.json.jado-tmp'); await writeFile(marker, 'foreign file');
  await assert.rejects(() => applyInstall(missingPlan, missingPlan.revision), /Temporary file/);
  assert.equal(await readFile(marker, 'utf8'), 'foreign file');
  await assert.rejects(() => readFile(path.join(missing, 'SKILL.md')), /ENOENT/, 'Rollback removes a partially installed upstream package');
  await rm(marker);
  await apply(missingPlan);
  assert((await readFile(path.join(missing, 'SKILL.md'), 'utf8')).endsWith('Fresh upstream package.\n'));
  const removedProcedure = async (name, record, skill, workspace) => {
    const fresh = await simulatedUpstream(name, record, skill, workspace);
    if (name === 'research') await rm(path.join(fresh.folder, 'SKILL.md'));
    return fresh;
  };
  await assert.rejects(() => prepareGlobal({ tools: ['codex','claude-code','opencode'], userRoot: home, loadPackage: removedProcedure }), /Missing upstream procedure/);
  const oldProfile = Buffer.from('Installed profile from the previous framework revision.\n');
  const oldInstructions = Buffer.from('Installed entry from the previous framework revision.\n');
  const earlier = JSON.parse(await readFile(path.join(home,'.jado/install.json')));
  for (const name of ['.jado/agents/codex/jado-agent-ux.toml','.codex/agents/jado-agent-ux.toml','.jado/instructions.md']) {
    const content = name.endsWith('.toml') ? oldProfile : oldInstructions;
    await writeFile(path.join(home,name),content);
    earlier.files[name] = {hash:hash(content),mode:0o644};
  }
  await writeFile(path.join(home,'.jado/install.json'),JSON.stringify(earlier));
  const methodBefore = await readFile(path.join(home, '.jado/jado/workflows.json'));
  const skillsOnly = await prepareGlobal({ tools: ['codex','claude-code','opencode'], userRoot: home, component: 'skills', loadPackage: simulatedUpstream });
  await apply(skillsOnly);
  assert((await readFile(path.join(home, '.jado/jado/workflows.json'))).equals(methodBefore));
  assert((await readFile(path.join(home,'.codex/agents/jado-agent-ux.toml'))).equals(oldProfile),'Upstream refresh preserves the installed native profile');
  assert((await readFile(path.join(home,'.jado/instructions.md'))).equals(oldInstructions),'Upstream refresh preserves framework instructions');
  const runtimeLock = JSON.parse(await readFile(path.join(home,'.jado/jado/skill-lock.json')));
  const badSource = structuredClone(runtimeLock); badSource.skills.impeccable.source = 'someone/else';
  await writeFile(path.join(home, '.agents/.skill-lock.json'), JSON.stringify(badSource));
  await apply(await prepareGlobal({tools:['codex','claude-code','opencode'],userRoot:home}));
  assert(!(JSON.parse(await readFile(path.join(home,'.agents/.skill-lock.json')))).skills.impeccable,'Foreign lock provenance cannot override the JADO source');
  await writeFile(path.join(home, '.agents/.skill-lock.json'), JSON.stringify(runtimeLock));
  const profilePath = path.join(home, '.codex/agents/jado-agent-frontend.toml');
  const profileBytes = await readFile(profilePath);
  await rm(profilePath);
  await assert.rejects(() => prepareLink({ target: product, userRoot: home }), /ENOENT/, 'Link checks actual native profile files');
  await writeFile(profilePath, profileBytes);
  const link = await prepareLink({ target: product, userRoot: home });
  await apply(link);
  assert.deepEqual((await readdir(product)).sort(), ['.jado', 'AGENTS.md', 'CLAUDE.md']);
  assert.deepEqual((await readdir(path.join(product, '.jado'))).sort(), ['install.json','instructions.md','migration.md']);
  assert(!(await readFile(path.join(product, 'AGENTS.md'), 'utf8')).includes(home), 'Project instructions contain no personal path');
  assert.equal((await prepareLink({ target: product, userRoot: home })).changes.length, 0);
  await writeFile(path.join(product, 'AGENTS.md'), '# New product rule\n' + await readFile(path.join(product, 'AGENTS.md'), 'utf8'));
  assert.equal((await prepareLink({ target: product, userRoot: home })).changes.length, 0, 'Unrelated instruction edits do not break updates');
  const badBlock = (await readFile(path.join(product, 'AGENTS.md'), 'utf8')).replace('# BEGIN JADO — managed design entry', '# BEGIN JADO — managed design entry\nChanged managed rule');
  await writeFile(path.join(product, 'AGENTS.md'), badBlock);
  await assert.rejects(() => prepareLink({ target: product, userRoot: home }), /JADO block modified/);
  const freshGlobal = await prepareGlobal({ tools: ['codex','claude-code','opencode'], userRoot: home });
  await writeFile(path.join(home, '.codex/config.toml'), await readFile(path.join(home, '.codex/config.toml'), 'utf8') + '\n# concurrent preferences\n');
  await assert.rejects(() => applyInstall(freshGlobal, freshGlobal.revision), /Destination changed/);
  await mkdir(path.join(home, '.agents/skills/unrelated')); await writeFile(path.join(home, '.agents/skills/unrelated/SKILL.md'), 'unrelated');
  const changedTools = await prepareGlobal({ tools: ['codex'], userRoot: home });
  await apply(changedTools);
  assert.equal(await readFile(path.join(home, '.agents/skills/unrelated/SKILL.md'), 'utf8'), 'unrelated');
  assert.equal((await readdir(path.join(home, '.claude/agents'))).length, 0, 'Deselecting a tool removes its owned roles only');
  const local = path.join(fixture, 'local'); await mkdir(local);
  await apply(await prepareInstall({ target: local, tools: ['codex'] }));
  await assert.rejects(() => prepareLink({ target: local, userRoot: home }), /complete local copy/);
  await assert.rejects(() => prepareLocalUpdate({ target: local, tools: ['claude-code'], component: 'skills' }), /change tools/);
  const installed = JSON.parse(await readFile(path.join(local, '.jado/install.json')));
  const rootResearch = path.join(local, '.jado/skills/research/SKILL.md');
  const originalResearch = await readFile(rootResearch);
  const fakeFetch = async (name, record, skill, workspace) => {
    const folder = path.join(workspace, name); await cp(path.join(local, '.jado/skills', name), folder, { recursive: true });
    await writeFile(path.join(folder, 'SKILL.md'), await readFile(path.join(folder, 'SKILL.md'), 'utf8') + '\nUpdated upstream.\n');
    return { folder, record: { ...record, skillFolderHash: hash(await readFile(path.join(folder, 'SKILL.md'))) } };
  };
  const update = await prepareLocalUpdate({ target: local, component: 'skills', loadPackage: fakeFetch });
  assert((await readFile(rootResearch)).equals(originalResearch), 'Update planning leaves the installed files untouched');
  await apply(update);
  assert((await readFile(rootResearch, 'utf8')).endsWith('Updated upstream.\n'));
  const beforeMethod = await readFile(rootResearch);
  await apply(await prepareLocalUpdate({ target: local, component: 'method' }));
  assert((await readFile(rootResearch)).equals(beforeMethod), 'Updating the method does not downgrade external skills to the source snapshot');
  await writeFile(rootResearch, 'personal edit');
  assert((await prepareLocalUpdate({target:local,component:'skills'})).changes.some(c => c.relative === '.jado/skills/research/SKILL.md'),'Explicit upstream refresh replaces managed package edits');
  assert(installed.files['.agents/skills/jado-flow']);
  const { stdout } = await run(process.execPath, ['scripts/jado/install.mjs','update','--component','method','--global','--user-root',home,'--agents','codex','--dry-run','--json']);
  assert.equal(JSON.parse(stdout).scope, 'global');
  assert.throws(() => managedBlock('# BEGIN JADO — managed design entry\nmissing end', 'body'), /Ambiguous/);
} finally {
  for (const backup of backups) await rm(backup, { recursive: true, force: true });
  await rm(fixture, { recursive: true, force: true });
}
console.log('JADO scopes: priority, directory backups, aliases, instructions, links, updates and stale plans verified.');
