import { readFile, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { parseArgs } from 'node:util';
import { profile, resolveAgents } from '../../lib/jado/render.ts';
const {values}=parseArgs({options:{export:{type:'string'}}});
const root = process.cwd();
const agents=resolveAgents(JSON.parse(await readFile('jado/agents.json','utf8')));
if(values.export){
 const out=path.resolve(values.export);
 await mkdir(out,{recursive:true});
 for(const agent of agents){
  const file=path.join(out,`${agent.id}.toml`);
  await writeFile(file,profile(agent,root),{flag:'wx'});
 }
 console.log(`Exported ${agents.length} profiles to ${out}. Install them explicitly in the target project’s .codex/agents directory; paths point to this JADO checkout.`);
}else{
 const file='.codex/config.toml';
 let old;
 try{old=await readFile(file,'utf8');}catch(e){if(e.code!=='ENOENT')throw e;}
 if(old&&!old.startsWith('# Generated by JADO'))throw new Error('Existing project configuration: overwrite refused. Integrate the MCP server manually.');
 await mkdir('.codex',{recursive:true});
 await writeFile(file,`# Generated by JADO; local paths, not committed. Reconfigure after moving the checkout.\n[mcp_servers.jado]\ncommand = ${JSON.stringify(process.execPath)}\nargs = [${JSON.stringify(path.join(root,'scripts/jado/mcp.mjs'))}, "--root", ${JSON.stringify(root)}]\n`);
 console.log('JADO MCP configured for this repository only. Open a new Codex chat in this project to load the configuration; no global changes.');
}
